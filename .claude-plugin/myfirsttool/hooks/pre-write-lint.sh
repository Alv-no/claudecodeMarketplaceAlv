#!/bin/bash
# pre-write-lint.sh — Block writes to protected files (lockfiles, .env, CI config, Dockerfile)
# Reads hook context JSON from stdin. Exits 2 + JSON to block, 0 to allow.

set -euo pipefail

INPUT="$(cat)"
PLUGIN_DIR="${CLAUDE_PROJECT_DIR:-.}/.claude/plugins/myfirsttool"
LOG_DIR="$PLUGIN_DIR/logs"
mkdir -p "$LOG_DIR"

# Extract the file path from the tool input
# PostToolUse/PreToolUse context has tool_input.file_path for Write, tool_input.file_path for Edit
FILE_PATH="$(echo "$INPUT" | jq -r '.tool_input.file_path // .tool_input.path // empty' 2>/dev/null || true)"

if [ -z "$FILE_PATH" ]; then
  exit 0
fi

BASENAME="$(basename "$FILE_PATH")"
LOWER_BASENAME="$(echo "$BASENAME" | tr '[:upper:]' '[:lower:]')"

BLOCKED=false
REASON=""

# Check lockfiles
case "$LOWER_BASENAME" in
  package-lock.json|yarn.lock|pnpm-lock.yaml|composer.lock|gemfile.lock|cargo.lock|poetry.lock|pipfile.lock|bun.lockb)
    BLOCKED=true
    REASON="Lockfile '$BASENAME' should be generated by the package manager, not written directly."
    ;;
esac

# Check .env files
case "$LOWER_BASENAME" in
  .env|.env.local|.env.production|.env.staging|.env.development|.env.*)
    BLOCKED=true
    REASON="Environment file '$BASENAME' may contain secrets and should not be modified by Claude."
    ;;
esac

# Check CI config files
case "$LOWER_BASENAME" in
  .gitlab-ci.yml|.travis.yml|jenkinsfile|buildkite.yml)
    BLOCKED=true
    REASON="CI configuration '$BASENAME' is a protected file. Modify manually."
    ;;
esac

# Check CI config in paths
case "$FILE_PATH" in
  */.github/workflows/*|*/.circleci/*)
    BLOCKED=true
    REASON="CI configuration in '$FILE_PATH' is protected. Modify manually."
    ;;
esac

# Check Dockerfile
case "$LOWER_BASENAME" in
  dockerfile|dockerfile.*|*.dockerfile)
    BLOCKED=true
    REASON="Dockerfile '$BASENAME' is a protected file. Modify manually."
    ;;
  docker-compose.yml|docker-compose.yaml|docker-compose.*.yml|docker-compose.*.yaml|compose.yml|compose.yaml)
    BLOCKED=true
    REASON="Docker Compose file '$BASENAME' is protected. Modify manually."
    ;;
esac

if [ "$BLOCKED" = true ]; then
  # Log the blocked attempt
  echo "{\"timestamp\":\"$(date -u +%Y-%m-%dT%H:%M:%SZ)\",\"action\":\"blocked\",\"file\":\"$FILE_PATH\",\"reason\":\"$REASON\"}" >> "$LOG_DIR/audit.jsonl"

  # Exit 2 with JSON to block the operation
  echo "{\"decision\":\"block\",\"reason\":\"$REASON\"}"
  exit 2
fi

exit 0
